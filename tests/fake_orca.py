#!/usr/bin/env python3
"""fake_orca.py — a stand-in for the OrcaSlicer CLI in tests: reads the assemble list (STLs of boxes) and
the settings files the translator wrote, and writes Bambu-style G-code and a .gcode.3mf whose
extrusion volume, layers, temperatures and placement follow those settings. FAKE_ORCA_MODE:
  ok (default) | fail17 (exit -17) | crash (killed by a signal) | shift (parts printed 6 mm off) | hot (+20 C nozzle)
  | overhang (each part's walls inset 6 mm except its top 2 layers, which hang over; with enable_support,
    support lines under them)
  | sleep (never ends, for timeouts and cancel)
Version: 2026.10.24.7
"""
import hashlib
import json
import math
import os
import signal
import sys
import time
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from print3d_translator import mesh as M  # noqa: E402


def arg(argv, key, default=None):
    return argv[argv.index(key) + 1] if key in argv else default


def first(v, d=0.0):
    if isinstance(v, list):
        v = v[0] if v else d
    try:
        return float(str(v).rstrip("%"))
    except (TypeError, ValueError):
        return d


def main(argv):
    if "--help" in argv:
        print("OrcaSlicer-2.4.2:\nUsage: orca-slicer [ OPTIONS ] [ file.3mf/file.stl ... ]")
        return 0
    mode = os.environ.get("FAKE_ORCA_MODE", "ok")
    if mode == "fail17":
        return 256 - 17
    if mode == "crash":
        os.kill(os.getpid(), signal.SIGKILL)   # SIGSEGV would make macOS write a crash report
    if mode == "sleep":
        time.sleep(600)
    machine, process = [json.loads(Path(p).read_text()) for p in arg(argv, "--load-settings").split(";")]
    fils = [json.loads(Path(p).read_text()) for p in arg(argv, "--load-filaments").split(";")]
    assemble = json.loads(Path(arg(argv, "--load-assemble-list")).read_text())
    out = Path(arg(argv, "--outputdir"))
    bed_type = arg(argv, "--curr-bed-type", "Textured PEI Plate")
    temp_key = {"Textured PEI Plate": "textured_plate_temp", "High Temp Plate": "hot_plate_temp",
                "Engineering Plate": "eng_plate_temp"}.get(bed_type, "textured_plate_temp")
    fmap = [int(x) for x in arg(argv, "--filament-map", "").split(",") if x]
    lh, h1 = first(process.get("layer_height"), 0.2), first(process.get("initial_layer_print_height"), 0.2)
    walls = first(process.get("wall_loops"), 2)
    ow, iw = first(process.get("outer_wall_line_width"), 0.42), first(process.get("inner_wall_line_width"), 0.45)
    dens = first(process.get("sparse_infill_density"), 15) / 100
    ttop = max(first(process.get("top_shell_layers"), 4) * lh, first(process.get("top_shell_thickness"), 0))
    nb = first(process.get("bottom_shell_layers"), 3)
    tbot = max(h1 + (nb - 1) * lh if nb >= 1 else 0, first(process.get("bottom_shell_thickness"), 0))
    area_f = math.pi * 0.875 ** 2
    objs = []
    for k, o in enumerate(assemble["plates"][0]["objects"]):
        tri = M.read_stl(o["path"])
        lo, hi = M.bbox(tri)
        if mode == "shift":
            lo[0] += 6
            hi[0] += 6
        sx, sy, sz = hi - lo
        V = sx * sy * sz
        shell = min(V, 2 * (sx + sy) * sz * (ow + (walls - 1) * iw) + sx * sy * (ttop + tbot))
        objs.append({"name": Path(o["path"]).stem + "_1", "tool": o["filaments"][0] - 1, "lo": lo, "hi": hi,
                     "model": shell + dens * (V - shell), "id": 100 + k})
    zs = [h1]
    top = max(o["hi"][2] for o in objs)
    while zs[-1] + lh <= top + 1e-6:
        zs.append(round(zs[-1] + lh, 4))
    tools = sorted({o["tool"] for o in objs})
    temps = {t: (first(fils[t].get("nozzle_temperature_initial_layer")) + (20 if mode == "hot" else 0),
                 first(fils[t].get("nozzle_temperature")) + (20 if mode == "hot" else 0)) for t in tools}
    beds = [first(fils[t].get(temp_key + "_initial_layer"), first(fils[t].get(temp_key))) for t in tools]
    bed = max(beds)
    formula = "by_highest_temp" if len(tools) > 1 else "by_first_filament"
    tower = None
    if len(tools) > 1 and process.get("wipe_tower_x"):
        tx, ty = first(process["wipe_tower_x"]), first(process["wipe_tower_y"])
        tower = (tx, ty, tx + 25, ty + 25)
    L = ["; HEADER_BLOCK_START", "; generated by fake_orca", "; model printing time: 10m 0s; total estimated time: 12m 30s",
         f"; total layer number: {len(zs)}", f"; max_z_height: {zs[-1]:.2f}", "; HEADER_BLOCK_END", "",
         "; CONFIG_BLOCK_START", f"; layer_height = {lh}", f"; bed_temperature_formula = {formula}",
         f"; filament_map = {','.join(map(str, fmap or [1] * len(fils)))}", "; CONFIG_BLOCK_END", "",
         "; EXECUTABLE_BLOCK_START", "M83", "G90", f"M140 S{bed:g}", "G28", f"T{tools[0]}",
         f"M104 S{temps[tools[0]][0]:g}", f"M190 S{bed:g}", f"M109 S{temps[tools[0]][0]:g}",
         "G1 X20 Y-0.5 Z0.8 F6000", "G1 X40 E5"]
    used = {t: 0.0 for t in range(len(fils))}
    used[tools[0]] += 5
    cur = tools[0]
    for n, z in enumerate(zs):
        L += ["; CHANGE_LAYER", f"; Z_HEIGHT: {z}", f"; LAYER_HEIGHT: {h1 if n == 0 else lh}"]
        if n == 1:
            for t in tools:
                if temps[t][1] != temps[t][0]:
                    L.append(f"M104 S{temps[t][1]:g} T{t}")
        for o in objs:
            if z > o["hi"][2] + 1e-6:
                continue
            if o["tool"] != cur:
                L += [f"M620 S{o['tool']}A", f"T{o['tool']}", f"M104 S{temps[o['tool']][0 if n == 0 else 1]:g} T{o['tool']}",
                      f"M621 S{o['tool']}A"]
                cur = o["tool"]
                if tower:
                    L += ["; FEATURE: Prime tower", f"G1 X{tower[0] + 2:.3f} Y{tower[1] + 2:.3f} Z{z}",
                          f"G1 X{tower[2] - 2:.3f} Y{tower[1] + 2:.3f} E0.5", f"G1 X{tower[2] - 2:.3f} Y{tower[3] - 2:.3f} E0.5"]
                    used[cur] += 1.0
            nlay = sum(1 for zz in zs if zz <= o["hi"][2] + 1e-6)
            e_layer = o["model"] / nlay / area_f
            (x0, y0), (x1, y1) = o["lo"][:2] + ow / 2, o["hi"][:2] - ow / 2
            L += [f"; printing object {o['name']} id:{o['id']} copy 0", f"G1 Z{z}"]
            if mode == "overhang" and z < o["hi"][2] - 2 * lh + 1e-6:
                if str(first(process.get("enable_support"), 0)).lower() in ("1", "true", "1.0"):
                    L += ["; FEATURE: Support", f"G1 X{x0:.3f} Y{y0:.3f}"]
                    yy, up = y0, True
                    while yy <= y1 + 1e-9:
                        L += [f"G1 X{(x1 if up else x0):.3f} Y{yy:.3f} E0.02", f"G1 Y{min(yy + 2.0, y1):.3f}"]
                        yy, up = yy + 2.0, not up
                x0, y0, x1, y1 = x0 + 6, y0 + 6, x1 - 6, y1 - 6
            per = 2 * ((x1 - x0) + (y1 - y0))
            L += ["; FEATURE: Outer wall", f"G1 X{x0:.3f} Y{y0:.3f}"]
            for (px, py, seg) in ((x1, y0, x1 - x0), (x1, y1, y1 - y0), (x0, y1, x1 - x0), (x0, y0, y1 - y0)):
                L.append(f"G1 X{px:.3f} Y{py:.3f} E{e_layer * seg / per:.5f}")
            used[cur] += e_layer
            L.append(f"; stop printing object {o['name']} id:{o['id']} copy 0")
    L += ["; FEATURE: Custom", "M140 S0", "M104 S0", "; EXECUTABLE_BLOCK_END", "",
          "; filament used [mm] = " + ", ".join(f"{used[t]:.2f}" for t in range(len(fils))),
          "; filament used [g] = " + ", ".join(f"{used[t] * area_f * first(fils[t].get('filament_density'), 1.24) / 1000:.2f}"
                                               for t in range(len(fils)))]
    g = ("\n".join(L) + "\n").encode()
    (out / "plate_1.gcode").write_bytes(g)
    project = {**machine, **process}
    # as OrcaSlicer: per-variant keys are expanded to the same variant count for every filament
    # (filament_self_index says whose entry is whose); other filament keys have one entry per filament
    nvar = max([len(v) for f in fils for v in f.values() if isinstance(v, list)] + [1])
    for key in sorted({k for f in fils for k in f}):
        vals = [f.get(key) for f in fils]
        if all(isinstance(v, list) and v for v in vals):
            if any(len(v) > 1 for v in vals):
                project[key] = [x for v in vals for x in (v + [v[-1]] * (nvar - len(v)))[:nvar]]
            else:
                project[key] = [v[0] for v in vals]
        elif len(fils) == 1:
            project[key] = vals[0]
    project["filament_self_index"] = [str(i + 1) for i in range(len(fils)) for _ in range(nvar)]
    project["filament_map"] = [str(x) for x in (fmap or [1] * len(fils))]
    noz = ",".join(machine.get("nozzle_diameter") or ["0.4"])
    si = ('<?xml version="1.0" encoding="UTF-8"?>\n<config>\n  <header><header_item key="X-BBL-Client-Type" value="slicer"/>'
          '</header>\n  <plate>\n    <metadata key="index" value="1"/>\n    <metadata key="printer_model_id" value=""/>\n'
          f'    <metadata key="nozzle_diameters" value="{noz}"/>\n    <metadata key="prediction" value="750"/>\n'
          f'    <metadata key="filament_maps" value="{" ".join(map(str, fmap or [1] * len(fils)))}"/>\n'
          + "".join(f'    <object identify_id="{o["id"]}" name="{o["name"]}" skipped="false" />\n' for o in objs)
          + "".join(f'    <filament id="{t + 1}" type="X" used_m="{used[t] / 1000:.2f}" used_g="1"/>\n' for t in tools)
          + '    <warning msg="fake_warning" level="1" error_code="0"/>\n  </plate>\n</config>\n')
    plate = {"bbox_objects": [{"name": o["name"], "bbox": [*o["lo"][:2].tolist(), *o["hi"][:2].tolist()]} for o in objs]}
    if tower:
        plate["bbox_objects"].append({"name": "wipe_tower", "bbox": list(tower)})
    with zipfile.ZipFile(out / arg(argv, "--export-3mf"), "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", "<Types/>")
        z.writestr("_rels/.rels", "<Relationships/>")
        z.writestr("3D/3dmodel.model", "<model/>")
        z.writestr("Metadata/plate_1.gcode", g)
        z.writestr("Metadata/plate_1.gcode.md5", hashlib.md5(g).hexdigest().upper())
        z.writestr("Metadata/slice_info.config", si)
        z.writestr("Metadata/model_settings.config", '<?xml version="1.0"?>\n<config></config>\n')
        z.writestr("Metadata/project_settings.config", json.dumps(project))
        z.writestr("Metadata/plate_1.json", json.dumps(plate))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
