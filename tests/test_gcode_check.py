def test_roundtrip_filament_variants():
    project = {"nozzle_temperature": ["220", "220", "250", "250"], "filament_self_index": ["1", "1", "2", "2"],
               "textured_plate_temp": ["55", "70"], "wall_loops": "3", "layer_height": "0.2"}
    fils = [{"nozzle_temperature": ["220", "220"], "textured_plate_temp": ["55"]},
            {"nozzle_temperature": ["250", "250"], "textured_plate_temp": ["70"]}]
    known = {"nozzle_temperature", "textured_plate_temp", "wall_loops", "layer_height"}
    r = A.roundtrip({}, {"wall_loops": "3", "layer_height": "0.2", "made_up": "1"}, fils, project, known)
