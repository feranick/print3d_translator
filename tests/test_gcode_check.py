def test_patch_resets_garbage_first_layer_time(tmp_path):
    g = b"; CHANGE_LAYER\nG1 X1 E1\n"
    p = make_archive(tmp_path / "f.3mf", g, model_id="N7")
    with zipfile.ZipFile(p) as z:
        items = {n: z.read(n) for n in z.namelist()}
