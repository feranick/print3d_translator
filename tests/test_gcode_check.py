def test_checks_catch_faults(kw, res_kw, obj_kw, fails):
    text, _, _ = synth(**kw)
    r = resolved(n_fil=2, **res_kw) if obj_kw.get("filament") == 2 else resolved(**res_kw)
    res = C.check_gcode(G.parse(text), r, [obj(**obj_kw)])
