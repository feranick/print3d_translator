def synth(box=(10.0, 10.0, 1.0), at=(50.0, 60.0), lh=0.2, h1=0.2, nozzle=220, bed=55, tool=0,
          extra_layer_lines="", prime=True, name="part_1"):
    """G-code for a box (2 perimeters + diagonal infill per layer), OrcaSlicer BBL style."""
    sx, sy, sz = box
    x0, y0 = at[0] - sx / 2, at[1] - sy / 2
    zs = [h1]
    while zs[-1] + lh <= sz + 1e-9:
        zs.append(round(zs[-1] + lh, 4))
    out = ["; HEADER_BLOCK_START", "; generated by synth", "; model printing time: 1m 2s; total estimated time: 2m 3s",
           f"; total layer number: {len(zs)}", "; filament_density: 1.26", "; filament_diameter: 1.75",
           f"; max_z_height: {zs[-1]:.2f}", "; HEADER_BLOCK_END", "", "; CONFIG_BLOCK_START",
           f"; layer_height = {lh}", f"; initial_layer_print_height = {h1}", "; bed_temperature_formula = by_first_filament",
           "; filament_map = 1", "; CONFIG_BLOCK_END", "", "; EXECUTABLE_BLOCK_START", "M83", "G90",
           f"M140 S{bed}", "G28", "M622 J1", "    M109 S180", "    G1 X5 Y5", "M623",
           f"T{tool}", f"M104 S{nozzle}", f"M190 S{bed}", f"M109 S{nozzle}"]
    e_total = 0.0
    if prime:
        out += ["G1 X20 Y-0.5 Z0.8 F6000", "G1 X40 E5"]
        e_total += 5
    w = 0.42
    k = 0.04                                    # E per mm of extrusion line
    for n, z in enumerate(zs):
        out += ["; CHANGE_LAYER", f"; Z_HEIGHT: {z}", f"; LAYER_HEIGHT: {h1 if n == 0 else lh}",
                f"; printing object {name} id:0 copy 0", f"G1 Z{z}", "; FEATURE: Outer wall"]
        for inset in (w / 2, 1.5 * w):
            a, b = x0 + inset, y0 + inset
            c, d = x0 + sx - inset, y0 + sy - inset
            out.append(f"G1 X{a:.3f} Y{b:.3f}")
            for (px, py, L) in ((c, b, c - a), (c, d, d - b), (a, d, c - a), (a, b, d - b)):
                out.append(f"G1 X{px:.3f} Y{py:.3f} E{L * k:.5f}")
                e_total += L * k
        out += ["; FEATURE: Sparse infill", f"G1 X{x0 + 2 * w:.3f} Y{y0 + 2 * w:.3f}"]
        L = math.hypot(sx - 4 * w, sy - 4 * w)
        out.append(f"G1 X{x0 + sx - 2 * w:.3f} Y{y0 + sy - 2 * w:.3f} E{L * k:.5f}")
        e_total += L * k
        out += [extra_layer_lines if n == 1 else "", f"; stop printing object {name} id:0 copy 0"]
    out += ["; FEATURE: Custom", "; machine end", "M140 S0", "M104 S0", "G1 X300 Y300", "; EXECUTABLE_BLOCK_END", "",
            f"; filament used [mm] = {e_total:.2f}", f"; filament used [g] = {e_total * G.filament_area() * 1.26 / 1000:.2f}"]
    return "\n".join(out) + "\n", zs, e_total


def resolved(lh=0.2, h1=0.2, walls=2, infill=15, bed=55, nozzle=220, n_fil=1, ext_areas=None):
    fil = {"filament_diameter": ["1.75"], "filament_density": ["1.26"], "nozzle_temperature": [str(nozzle)],
           "nozzle_temperature_initial_layer": [str(nozzle)], "nozzle_temperature_range_low": ["190"],
           "nozzle_temperature_range_high": ["240"], "textured_plate_temp": [str(bed)],
           "textured_plate_temp_initial_layer": [str(bed)]}
    m = {"printable_area": ["0x0", "256x0", "256x256", "0x256"], "printable_height": "256"}
    if ext_areas:
        m["extruder_printable_area"] = ext_areas
    return {"machine": m,
            "process": {"layer_height": str(lh), "initial_layer_print_height": str(h1), "wall_loops": str(walls),
                        "sparse_infill_density": f"{infill}%", "outer_wall_line_width": "0.42",
                        "inner_wall_line_width": "0.42", "top_shell_layers": "0", "bottom_shell_layers": "0",
                        "brim_type": "no_brim", "brim_width": "0"},
            "filaments": [copy.deepcopy(fil) for _ in range(n_fil)],
            "plate": {"name": "textured_pei", "bed_type": "Textured PEI Plate", "temp_key": "textured_plate_temp"}}


def obj(box=(10.0, 10.0, 1.0), at=(50.0, 60.0), name="part_1", filament=1):
    return {"name": name, "filament": filament, "tri": M.place(M.box(*box), at)}


# ------------------------------------------------------------- parser

def test_parse_regions_layers_and_totals():
    text, zs, e = synth()
    P = G.parse(text)
    assert [l["z_height"] for l in P.layers] == zs
    assert np.allclose(G.print_z_levels(P), zs)
    assert P.header["layers"] == len(zs) and P.header["total_time_s"] == 123
    assert P.marks["first_layer"] is not None and P.marks["end_block"] is not None
    assert P.objects == ["part_1"]
    located = P.segments[:, 5].sum()
    assert located + sum(P.e_unlocated.values()) == pytest.approx(e, abs=1e-3)
    assert P.footer["filament used [mm]"][0] == pytest.approx(e, abs=0.01)
    assert P.relative_e is True


def test_unknown_position_after_homing_and_conditional_block():
    text, _, _ = synth()
    P = G.parse(text)
    # the prime line follows G28 and a conditional move: the first move sets X/Y/Z, so it is located
    assert P.unlocated_by_region.get("print", 0) == 0
    # the conditional M109 S180 is recorded but not applied
    cond = [t for t in P.temps if t["conditional"]]
    assert cond and cond[0]["value"] == 180


def test_unlocated_extrusion_is_counted():
    P = G.parse("M83\nG28\nG1 X10 E2\n; CHANGE_LAYER\n; Z_HEIGHT: 0.2\nG1 X20 E1\n")
    assert P.unlocated_by_region == {"start": 2.0, "print": 1.0}


def test_relative_positioning_and_absolute_e():
    P = G.parse("G90\nM82\nG92 E0\nG1 X0 Y0 Z0.2\n; CHANGE_LAYER\nG91\nG1 X10 E1\nG1 Y10 E2\nG90\nG1 X0 E2.5\n")
    s = P.segments
    assert np.allclose(s[:, :4], [[0, 0, 10, 0], [10, 0, 10, 10], [10, 10, 0, 10]])
    assert np.allclose(s[:, 5], [1, 1, 0.5])


def test_arcs_full_circle_and_helix():
    P = G.parse("M83\nG1 X10 Y0 Z0.2\n; CHANGE_LAYER\nG3 X10 Y0 I-10 J0 E6.28\nG2 X0 Y10 I-10 J0 E1\n")
    pts = np.vstack([P.segments[:, 0:2], P.segments[:, 2:4]])
    assert pts[:, 0].min() == pytest.approx(-10, abs=0.1) and pts[:, 1].min() == pytest.approx(-10, abs=0.1)
    assert P.segments[:, 5].sum() == pytest.approx(7.28)
    H = G.parse("M83\nG1 X1 Y0 Z0.2\n; CHANGE_LAYER\nG3 Z0.6 I-1 J0 P1\n")       # Z-hop helix, no extrusion
    assert len(H.segments) == 0


def test_tools_and_bambu_filament_change():
    text = ("M83\nG1 X0 Y0 Z0.2\nT0\nM104 S220\n; CHANGE_LAYER\nG1 X1 E1\n"
            "M620 S1A\nM620.10 A0 F600 L0 H0.4 T240 P220 S1\nM620.10 A1 F600 L0 H0.4 T260 P250 S1\nT1\nM621 S1A\n"
            "G1 X2 E1\nT1000\nT65535\n")
    P = G.parse(text)
    assert [t["tool"] for t in P.tool_changes] == [0, 1]
    inc = [t for t in P.temps if t["kind"] == "nozzle_change" and t["flags"] == ["A1"]][0]
    assert inc["tool"] == 1 and inc["value"] == 250 and inc["flush"] == 260
    assert sorted(set(P.seg_info[:, 1])) == [0, 1]


